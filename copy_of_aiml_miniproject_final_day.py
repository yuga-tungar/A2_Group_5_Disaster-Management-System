def _is_distress_text(text):
    distress_keywords = ["help", "please", "panic", "scared", "fear", "emergency", "save", "urgent", "danger", "sos"]
    text = (text or "").lower()
    return any(k in text for k in distress_keywords)


def _sanitize_history(history):
    if history is None:
        return []
    out = []
    for item in history:
        if isinstance(item, dict) and 'role' in item and 'content' in item:
            out.append(item)
        elif isinstance(item, (list, tuple)) and len(item) == 2:
            role, content = item
            out.append({"role": role, "content": content})
        else:
            out.append({"role": "assistant", "content": str(item)})
    return out


def _last_assistant_message(history):
    for item in reversed(history or []):
        if item.get("role") == "assistant":
            return item.get("content", "")
    return ""


def chat_response(history, user_msg, lat_value, lon_value):
    history = _sanitize_history(history)
    user_msg = (user_msg or "").strip()
    user_lower = user_msg.lower()

    if user_msg == "":
        user_msg = ""
        user_lower = ""

    if user_msg:
        last = history[-1] if history else None
        if not (last and last.get("role") == "user" and last.get("content") == user_msg):
            history.append({"role": "user", "content": user_msg})

    assistant_reply = ""

    # If user is clearly in distress, immediate comforting message + try SOS if location available
    if _is_distress_text(user_msg):
        assistant_reply = (
            "💛 Hey — I know this feels frightening. You're not alone. "
            "Take a slow, deep breath with me: inhale… 2… 3… exhale… 2… 3…\n\n"
            "I will stay with you and guide every step."
        )
        # If location provided, run SOS and include summary
        if lat_value is not None and lon_value is not None:
            try:
                risk_text, rescue_text, tips, map_html = sos(lat_value, lon_value)
                # Keep reply concise in chat — map will appear in SOS panel if user presses SOS
                assistant_reply += "\n\n" + risk_text + "\n\n" + rescue_text.split('\n')[0]
                assistant_reply += "\n\n(Press the **SOS** button to view the full deployment plan and map.)"
            except Exception as e:
                assistant_reply += "\n\n(I attempted to compute SOS info but encountered an error.)"

    # If location missing, gently ask to get location
    elif lat_value is None or lon_value is None:
        assistant_reply = (
            "📍 I want to help you safely, but I need your location. "
            "Please press **Get My Location** — I will only use it to find nearby help. "
            "If you can't, tell me what's happening and I will guide you the best I can."
        )

    # Intent: check risk
    elif any(k in user_lower for k in ["risk", "flood", "check"]):
        assistant_reply = (
            f"🌧️ I see your location (Lat: {lat_value}, Lon: {lon_value}). "
            "Press **SOS** now and I'll compute your flood risk right away and show the safest route. "
            "Stay as calm as possible — keep your phone with you and don't move into floodwater."
        )

    # Intent: nearest rescue
    elif any(k in user_lower for k in ["rescue", "center", "nearest", "help nearby"]):
        # compute a light-weight nearest center summary
        try:
            centers_df["distance_km"] = centers_df.apply(
                lambda r: great_circle((lat_value, lon_value), (r["Latitude"], r["Longitude"])).km, axis=1
            )
            nc = centers_df.loc[centers_df["distance_km"].idxmin()]
            assistant_reply = (
                f"🚑 Nearest center: {nc['Center_ID']} ({nc.get('risk_level','')}) — {nc['distance_km']:.2f} km away. "
                "Press **SOS** to see route and deployment plan."
            )
        except Exception:
            assistant_reply = (
                "🚑 I'll find the nearest rescue center for you. Press **SOS** and I'll show where to go and how far it is. "
                "If you're alone, try to inform someone you trust about your location."
            )

    # Intent: route / map
    elif any(k in user_lower for k in ["route", "safe route", "map", "path"]):
        assistant_reply = (
            "🗺️ I will generate the safest route for you when you press **SOS**. "
            "Follow the route slowly and avoid walking through moving water. "
            "If at any point you feel unsafe, stop and call for help."
        )

    # Intent: safety tips
    elif any(k in user_lower for k in ["tip", "safety", "advice", "what to do"]):
        tips_list = safety_tips.get("High") if "High" in safety_tips else None
        if not tips_list:
            tips_list = [
                "Move to higher ground immediately",
                "Avoid bridges or flooded roads",
                "Do not walk through moving water",
                "Keep your phone charged and flashlight ready",
                "Listen to local authorities and rescue teams"
            ]
        assistant_reply = "🛟 Stay calm — here are the most important steps:\n" + "\n".join([f"- {t}" for t in tips_list])

    # Default friendly helper message with suggestions
    else:
        assistant_reply = (
            "💛 I'm here with you. I can:\n"
            "• Check your flood risk\n"
            "• Find nearest rescue center\n"
            "• Show the safest route\n"
            "• Give safety tips\n\n"
            "Try the quick questions below, or type how you're feeling and I'll respond."
        )

    # Prevent repeating same assistant reply twice in a row
    last_assistant = _last_assistant_message(history)
    if assistant_reply.strip() != last_assistant.strip():
        history.append({"role": "assistant", "content": assistant_reply})
    else:
        assistant_reply = last_assistant

    return history, assistant_reply


