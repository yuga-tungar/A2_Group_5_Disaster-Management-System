def allocate_fleets_across_centers(centers_df_input, start_point, fleets_needed):
    df = centers_df_input.copy()
    df['dist'] = df.apply(lambda r: great_circle(start_point, (r["Latitude"], r["Longitude"])).km, axis=1)
    centers_sorted = df.sort_values('dist').copy()
    allocation = []
    remaining = int(fleets_needed)
    for _, row in centers_sorted.iterrows():
        if remaining <= 0:
            break
        can_send = int(min(row.get('capacity_fleets', 0), remaining))
        if can_send > 0:
            allocation.append({
                'Center_ID': row['Center_ID'],
                'risk': row['risk_level'],
                'distance_km': round(row['dist'], 2),
                'fleets': can_send
            })
        remaining -= can_send
    return allocation


def densify_corridor(df, start, goal, model, step_km=5.0, width_km=25.0):
    # Create evenly spaced samples along straight line + lateral offsets
    total_km = great_circle(start, goal).km
    n_steps = int(max(1, math.ceil(total_km / step_km)))
    extra = []
    lat1, lon1 = start
    lat2, lon2 = goal
    safe_wl = df['Water Level (m)'].median() if 'Water Level (m)' in df.columns else 0.0
    safe_dis = df['River Discharge (m³/s)'].median() if 'River Discharge (m³/s)' in df.columns else 0.0
    safe_elv = df['Elevation (m)'].median() if 'Elevation (m)' in df.columns else 0.0

    for i in range(1, n_steps):
        frac = i / n_steps
        ilat = lat1 + frac * (lat2 - lat1)
        ilon = lon1 + frac * (lon2 - lon1)
        extra.append((ilat, ilon, safe_wl, safe_dis, safe_elv))
        for side in [-1, 1]:
            dlat = (width_km / 111.0) * side
            extra.append((ilat + dlat, ilon, safe_wl, safe_dis, safe_elv))
            # small diagonal offset
            dlon = (width_km / 111.0) * 0.5 * side
            extra.append((ilat + dlat, ilon + dlon, safe_wl, safe_dis, safe_elv))

    if len(extra) == 0:
        return df.copy()

    extra_df = pd.DataFrame(extra, columns=[
        "Latitude", "Longitude",
        "Water Level (m)", "River Discharge (m³/s)", "Elevation (m)"
    ])

    # Predict labels: handle both numeric/string models
    Xpred = extra_df[[ 'River Discharge (m³/s)', 'Elevation (m)', 'Water Level (m)']]
    preds = model.predict(Xpred)
    if has_label_encoder:
        # numeric encoded -> convert to text
        extra_df['risk_label'] = label_encoder.inverse_transform(preds)
    else:
        extra_df['risk_label'] = preds

    return pd.concat([df.reset_index(drop=True), extra_df.reset_index(drop=True)], ignore_index=True)

# Neighbors with bigger radius to ensure connectivity
def neighbors(tree, coords, p, r_km=80):
    r_deg = r_km / 111.0
    idxs = tree.query_radius(np.array(p).reshape(1, -1), r=r_deg)[0]
    return [(float(coords[i][0]), float(coords[i][1])) for i in idxs]

def nearest(tree, coords, point):
    d, i = tree.query(np.array(point).reshape(1, -1), k=1)
    c = coords[i[0][0]]
    return (float(c[0]), float(c[1]))

def haversine(p1, p2):
    return great_circle(p1, p2).km

def risk_cost_point(df, coords, tree, point):
    d, i = tree.query(np.array(point).reshape(1, -1), k=1)
    label = df.iloc[i[0][0]]['risk_label']
    return RISK_COST.get(label, 6)

def a_star(tree, df, coords, start, goal, alpha=1.0, tol_km=0.2):
    # map start/goal to nearest graph nodes
    start_node = nearest(tree, coords, start)
    goal_node = nearest(tree, coords, goal)
    if start_node == goal_node:
        # nudge goal slightly to create a small path
        goal_node = (goal_node[0] + 0.0005, goal_node[1] + 0.0005)

    openh = [(0, start_node)]
    came = {}
    gscore = {start_node: 0}

    while openh:
        _, curr = heapq.heappop(openh)
        if haversine(curr, goal_node) <= tol_km:
            path = [curr]
            while curr in came:
                curr = came[curr]
                path.append(curr)
            return path[::-1]
        for nb in neighbors(tree, coords, curr, r_km=80):
            if nb == curr:
                continue
            d = haversine(curr, nb)
            cost = d + risk_cost_point(df, coords, tree, nb)
            ng = gscore[curr] + cost
            if nb not in gscore or ng < gscore[nb]:
                came[nb] = curr
                gscore[nb] = ng
                f = ng + haversine(nb, goal_node) + alpha * risk_cost_point(df, coords, tree, nb)
                heapq.heappush(openh, (f, nb))
    return None


